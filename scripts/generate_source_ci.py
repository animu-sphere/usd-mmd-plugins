"""Render OST source jobs and adapt them to a reusable, result-checked workflow.

The adapter only replaces the trigger, removes the original event guards and
adds a result check. Build/test/package steps remain OST renderer output.
Requires PyYAML==6.0.2. Use --bootstrap to fetch the manifest-pinned OST CLI.
"""

from __future__ import annotations

import argparse
import hashlib
import io
from pathlib import Path
import platform
import subprocess
import tarfile
import tempfile
import urllib.request
import zipfile

import yaml


ROOT = Path(__file__).resolve().parents[1]
WORKFLOW = ROOT / ".github/workflows/ost-source-ci.yml"


def adapt(raw: str) -> str:
    # BaseLoader deliberately keeps GitHub's `on` key and scalar text intact.
    data = yaml.load(raw, Loader=yaml.BaseLoader)
    if list(data["on"]) != ["pull_request"]:
        raise ValueError("Adapter supports a PR-only source matrix; review new lanes explicitly")
    jobs = data["jobs"]
    if not jobs or "source-result" in jobs:
        raise ValueError("Unexpected source job inventory")
    for job in jobs.values():
        if job.get("if") != "github.event_name == 'pull_request'":
            raise ValueError("Unexpected source event guard")
    if raw.count("on:\n  pull_request:\n") != 1:
        raise ValueError("Unexpected source trigger layout")
    guard = "    if: github.event_name == 'pull_request'\n"
    if raw.count(guard) != len(jobs):
        raise ValueError("Unexpected source job guard layout")
    rendered = raw.replace("on:\n  pull_request:\n", "on:\n  workflow_call:\n", 1)
    rendered = rendered.replace(guard, "")
    rendered = rendered.replace(
        "# Generated by `ost ci generate github` from openstrata.ci.yaml.\n",
        "# Generated by scripts/generate_source_ci.py from openstrata.ci.yaml.\n"
        "# OST owns the source jobs; the adapter owns workflow_call and source-result.\n", 1,
    )
    return rendered.rstrip() + "\n" + f"""
  source-result:
    name: source contracts
    if: always()
    needs: [{', '.join(jobs)}]
    runs-on: ubuntu-24.04
    steps:
      - name: Require every source job group to succeed
        env:
          SOURCE_NEEDS: ${{{{ toJSON(needs) }}}}
        run: |
          python3 - <<'PY'
          import json, os
          results = json.loads(os.environ['SOURCE_NEEDS'])
          if not results or any(job['result'] != 'success' for job in results.values()):
              raise SystemExit('A required source job failed, was cancelled or was skipped')
          PY
"""


def download_ost(directory: Path, pin: dict) -> str:
    triples = {
        ("Windows", "AMD64"): ("x86_64-pc-windows-msvc", "zip"),
        ("Linux", "x86_64"): ("x86_64-unknown-linux-musl", "tar.xz"),
        ("Darwin", "arm64"): ("aarch64-apple-darwin", "tar.xz"),
        ("Darwin", "x86_64"): ("x86_64-apple-darwin", "tar.xz"),
    }
    triple, extension = triples[(platform.system(), platform.machine())]
    asset = f"ost-cli-{triple}.{extension}"
    base = f"https://github.com/{pin['repository']}/releases/download/v{pin['version']}"
    with urllib.request.urlopen(f"{base}/{asset}", timeout=60) as response:
        archive = response.read()
    with urllib.request.urlopen(f"{base}/{asset}.sha256", timeout=30) as response:
        checksum = response.read().decode("ascii").split()[0]
    digest = hashlib.sha256(archive).hexdigest()
    if digest != checksum:
        raise ValueError("OST release checksum mismatch")
    pinned = pin.get("sha256", {}).get(triple)
    if pinned and digest != pinned:
        raise ValueError("OST checksum differs from manifest pin")
    name = "ost.exe" if platform.system() == "Windows" else "ost"
    if asset.endswith(".zip"):
        with zipfile.ZipFile(io.BytesIO(archive)) as package:
            entries = [entry for entry in package.namelist() if Path(entry).name == name]
            if len(entries) != 1:
                raise ValueError("Expected one OST executable")
            binary = package.read(entries[0])
    else:
        with tarfile.open(fileobj=io.BytesIO(archive)) as package:
            entries = [entry for entry in package.getmembers()
                       if entry.isfile() and Path(entry.name).name == name]
            if len(entries) != 1:
                raise ValueError("Expected one OST executable")
            binary = package.extractfile(entries[0]).read()
    destination = directory / name
    destination.write_bytes(binary)
    destination.chmod(0o755)
    return str(destination)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ost", default="ost")
    parser.add_argument("--bootstrap", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    manifest = yaml.safe_load((ROOT / "openstrata.ci.yaml").read_text(encoding="utf-8"))
    pin = manifest["bootstrap"]["ost"]
    with tempfile.TemporaryDirectory(prefix="mmd-ci-render-") as scratch:
        ost = download_ost(Path(scratch), pin) if args.bootstrap else args.ost
        version = subprocess.check_output([ost, "--version"], text=True).strip()
        if version != f"ost {pin['version']}":
            raise ValueError(f"Use the manifest-pinned ost {pin['version']}, got {version}")
        raw = subprocess.check_output(
            [ost, "ci", "generate", "github", "--stdout"], cwd=ROOT,
            text=True, encoding="utf-8", timeout=60,
        )
        rendered = adapt(raw)
    if args.check:
        if WORKFLOW.read_text(encoding="utf-8") != rendered:
            raise SystemExit("Source CI drift: run python scripts/generate_source_ci.py --bootstrap")
        print("Source CI matches the manifest and adapter.")
    else:
        WORKFLOW.write_text(rendered, encoding="utf-8", newline="\n")
        print(f"Generated {WORKFLOW}")


if __name__ == "__main__":
    main()
